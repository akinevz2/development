def открой_бд(путь: str) -> sqlite3.Connection:
    бд = sqlite3.connect(путь)
    бд.row_factory = sqlite3.Row
    бд.execute("PRAGMA journal_mode=WAL")
    бд.execute("PRAGMA foreign_keys=ON")
    бд.executescript("""
        CREATE TABLE IF NOT EXISTS термины (
            ид          INTEGER PRIMARY KEY AUTOINCREMENT,
            слово       TEXT    NOT NULL UNIQUE COLLATE NOCASE,
            перевод     TEXT    NOT NULL,
            пример      TEXT    DEFAULT '',
            теги        TEXT    DEFAULT '',
            добавлен    TEXT    NOT NULL DEFAULT (datetime('now'))
        );
        CREATE VIRTUAL TABLE IF NOT EXISTS термины_fts
            USING fts5(слово, перевод, пример, content='термины', content_rowid='ид');
        CREATE TRIGGER IF NOT EXISTS термины_ai AFTER INSERT ON термины BEGIN
            INSERT INTO термины_fts(rowid, слово, перевод, пример)
            VALUES (new.ид, new.слово, new.перевод, new.пример);
        END;
        CREATE TRIGGER IF NOT EXISTS термины_ad AFTER DELETE ON термины BEGIN
            INSERT INTO термины_fts(термины_fts, rowid, слово, перевод, пример)
            VALUES ('delete', old.ид, old.слово, old.перевод, old.пример);
        END;
        CREATE TRIGGER IF NOT EXISTS термины_au AFTER UPDATE ON термины BEGIN
            INSERT INTO термины_fts(термины_fts, rowid, слово, перевод, пример)
            VALUES ('delete', old.ид, old.слово, old.перевод, old.пример);
            INSERT INTO термины_fts(rowid, слово, перевод, пример)
            VALUES (new.ид, new.слово, new.перевод, new.пример);
        END;
        CREATE TABLE IF NOT EXISTS спор_сессии (
            ид          INTEGER PRIMARY KEY AUTOINCREMENT,
            исходник    TEXT    NOT NULL,
            финал       TEXT    NOT NULL,
            витков      INTEGER NOT NULL DEFAULT 0,
            модель      TEXT    NOT NULL DEFAULT '',
            создан      TEXT    NOT NULL DEFAULT (datetime('now'))
        );
        CREATE TABLE IF NOT EXISTS спор_витки (
            ид          INTEGER PRIMARY KEY AUTOINCREMENT,
            сессия_ид   INTEGER NOT NULL REFERENCES спор_сессии(ид),
            номер       INTEGER NOT NULL,
            вариант     TEXT    NOT NULL,
            замечание   TEXT    NOT NULL DEFAULT '',
            от_кого     TEXT    NOT NULL DEFAULT 'модель'
        );
        CREATE TABLE IF NOT EXISTS стиль_правила (
            ид          INTEGER PRIMARY KEY AUTOINCREMENT,
            правило     TEXT    NOT NULL UNIQUE,
            источник_ид INTEGER REFERENCES спор_сессии(ид),
            вес         INTEGER NOT NULL DEFAULT 1,
            добавлен    TEXT    NOT NULL DEFAULT (datetime('now'))
        );
    """)
    бд.commit()
    return бд


