def экс(бд, части):
    путь = части[1] if len(части) > 1 else f"рунисч-глоссарий-{datetime.now():%Y%m%d}.md"
    строки = бд.execute("SELECT * FROM термины ORDER BY слово").fetchall()
    with open(путь, "w", encoding="utf-8") as ф:
        ф.write(f"# Рунисч-Глоссарий\n\n*экспорт: {datetime.now():%Y-%m-%d %H:%M}*\n\n")
        текущ_тег = None
        for р in строки:
            первый_тег = р['теги'].split(",")[0].strip() if р['теги'] else "разное"
            if первый_тег != текущ_тег:
                текущ_тег = первый_тег
                ф.write(f"\n## {текущ_тег}\n\n")
            ф.write(f"### `{р['слово']}`\n")
            ф.write(f"**{р['перевод']}**\n\n")
            if р['пример']:
                ф.write(f"> {р['пример']}\n\n")
    print(f"[→] экспортировано {len(строки)} терминов → {путь}")


