def оллама_запрос(подсказка: str, систем: str | None = None) -> str:
    """Отправить запрос к Ollama /api/generate, вернуть текст ответа"""
    тело = {
        "model":  _оллама_модель,
        "prompt": подсказка,
        "stream": False,
    }
    if систем:
        тело["system"] = систем
    данные = json.dumps(тело).encode()
    запрос = urllib.request.Request(
        f"{_оллама_адрес}/api/generate",
        data=данные,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(запрос, timeout=ОЛЛАМА_ТАЙМАУТ) as отв:
            результат = json.loads(отв.read())
            return результат.get("response", "").strip()
    except urllib.error.URLError as е:
        raise ConnectionError(f"Оллама недоступна по {_оллама_адрес}: {е}") from е


def оллама_список_моделей() -> list[str]:
    """Получить список доступных моделей"""
    запрос = urllib.request.Request(
        f"{_оллама_адрес}/api/tags",
        method="GET",
    )
    try:
        with urllib.request.urlopen(запрос, timeout=10) as отв:
            данные = json.loads(отв.read())
            return [м["name"] for м in данные.get("models", [])]
    except Exception:
        return []


